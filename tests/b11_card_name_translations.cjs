/* B11 uses audited sheet translations only for visible names, never engine keys. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('web/client.js','utf8');
const start=source.indexOf('const CARD_ENGLISH_NAMES=');
const end=source.indexOf('const $=id=>',start);
assert(start>=0&&end>start);
const english=vm.runInNewContext(source.slice(start,end)+';displayCardName');
assert.equal(english('Yorikiri'),'Yorikiri (Force Out)');
assert.equal(english('Oshidashi'),'Oshidashi (Push Out)');
assert.equal(english('Yoritaoshi'),'Yoritaoshi (Crush Out)');
assert.equal(english('Hikiotoshi'),'Hikiotoshi (Pull Down)');
assert.equal(english('Utchari'),'Utchari (Edge Pivot Throw)');
assert.equal(english('Tsukitaoshi'),'Tsukitaoshi (Thrust Down)');
assert.equal(english('Tsukiotoshi'),'Tsukiotoshi (Thrust Down)');
assert.equal(english('Nodowa'),'Nodowa (Throat Grab)');
assert.equal(english('Tsuppari'),'Tsuppari (Repeated Thrusts)');
assert.equal(english('Tsuriotoshi'),'Tsuriotoshi (Lift and Drop)');
assert.equal(english('Gaburi'),'Hug and Chug (Gaburi)');
assert(source.includes('o.value=c.name'),'native select values remain canonical');
assert(source.includes('d.picks.push(c.name)'),'draft choices remain canonical');
assert(source.includes("type:'choose_cards',indices:acceptAll?options.map((_,i)=>i):[...picked]"),'kept-card choices retain original card identity');
console.log('Audited B11 English display names and canonical engine keys passed.');
